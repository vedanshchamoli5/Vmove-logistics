import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const localesDir = path.join(projectRoot, 'src', 'i18n', 'locales');

// Import existing en
import { en } from '../src/i18n/locales/en.ts';

// Helper to write a locale file
function writeLocaleFile(code, dict) {
  // Ensure every key in en exists in dict; fallback to en[key] if missing
  const completeDict = {};
  for (const key of Object.keys(en)) {
    completeDict[key] = dict[key] || en[key];
  }

  const content = `// Vmove Logistics - Multilingual Locale: ${code}
export const ${code}: Record<string, string> = ${JSON.stringify(completeDict, null, 2)};
`;

  const targetPath = path.join(localesDir, `${code}.ts`);
  fs.writeFileSync(targetPath, content, 'utf8');
  console.log(`Wrote locale file for: ${code} (${Object.keys(completeDict).length} keys)`);
}

